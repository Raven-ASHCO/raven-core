class ActiveAdvisoryAcceptanceTests(AuditWorld):
    """An advisory against a package in the build graph passes only with an exact, reviewed acceptance."""

    def setUp(self) -> None:
        super().setUp()
        self.advisories = {("plain", "2.0.0"): "RUSTSEC-TEST-0003"}

    def acceptance(self, **changes) -> dict:
        entry = {
            "advisory_id": "RUSTSEC-TEST-0003",
            "package": "plain",
            "version": "2.0.0",
            "review_by": soon(),
            "reachability": "only the verify path of plain is used",
            "reason": "no fixed release exists",
        }
        entry.update(changes)
        return {key: value for key, value in entry.items() if value is not None}

    def test_an_active_vulnerability_without_an_acceptance_still_fails(self) -> None:
        code, _, err, _ = self.audit_main()
        self.assertEqual(code, 1, err)
        self.assertIn("ACTIVE VULNERABILITY RUSTSEC-TEST-0003: plain v2.0.0", err)

    def test_an_accepted_active_vulnerability_passes_and_is_named(self) -> None:
        self.accepted = [self.acceptance()]
        code, out, err, _ = self.audit_main()
        self.assertEqual(code, 0, err)
        self.assertIn("accepted active advisory RUSTSEC-TEST-0003: plain v2.0.0", out)
        self.assertIn("only the verify path of plain is used", out)

    def test_an_accepted_vulnerability_in_a_fork_passes(self) -> None:
        self.advisories = {("forked", "1.0.0"): "RUSTSEC-TEST-0003"}
        self.accepted = [self.acceptance(package="forked", version="1.0.0")]
        code, _, err, _ = self.audit_main()
        self.assertEqual(code, 0, err)

    def test_an_acceptance_needs_a_reachability_rationale(self) -> None:
        self.accepted = [self.acceptance(reachability=None)]
        code, _, err, _ = self.audit_main()
        self.assertEqual(code, 2, err)

    def test_an_acceptance_needs_a_reason(self) -> None:
        self.accepted = [self.acceptance(reason="  ")]
        code, _, err, _ = self.audit_main()
        self.assertEqual(code, 2, err)

    def test_an_expired_acceptance_fails(self) -> None:
        self.accepted = [self.acceptance(review_by=(dt.date.today() - dt.timedelta(days=1)).isoformat())]
        code, _, err, _ = self.audit_main()
        self.assertEqual(code, 2, err)
        self.assertIn("expired", err)

    def test_an_acceptance_reviewed_too_far_ahead_fails(self) -> None:
        later = dt.date.today() + dt.timedelta(days=audit.MAX_ACTIVE_REVIEW_DAYS + 1)
        self.accepted = [self.acceptance(review_by=later.isoformat())]
        code, _, err, _ = self.audit_main()
        self.assertEqual(code, 2, err)
        self.assertIn("days ahead", err)

    def test_a_stale_acceptance_fails(self) -> None:
        self.advisories = {}
        self.accepted = [self.acceptance()]
        code, _, err, _ = self.audit_main()
        self.assertEqual(code, 1, err)
        self.assertIn("STALE ACTIVE ADVISORY ACCEPTANCE RUSTSEC-TEST-0003: plain v2.0.0", err)

    def test_an_acceptance_for_a_package_outside_the_build_graph_fails(self) -> None:
        self.active = {("app", "0.1.1"), ("forked", "1.0.0+raven.1")}
        self.accepted = [self.acceptance()]
        code, _, err, _ = self.audit_main()
        self.assertEqual(code, 1, err)
        self.assertIn("ACTIVE ADVISORY ACCEPTANCE FOR A PACKAGE OUTSIDE THE BUILD GRAPH RUSTSEC-TEST-0003", err)

    def test_one_advisory_cannot_be_both_accepted_and_excepted(self) -> None:
        self.accepted = [self.acceptance()]
        self.inactive = [
            {"advisory_id": "RUSTSEC-TEST-0003", "package": "plain", "version": "2.0.0", "review_by": soon(),
             "reason": "lock only"}
        ]
        code, _, err, _ = self.audit_main()
        self.assertEqual(code, 2, err)
        self.assertIn("RUSTSEC-TEST-0003", err)


class RepositoryLockTests(unittest.TestCase):
    """The real node/Cargo.lock, node/third_party/forks.json and policy (no cargo run)."""

    NODE = Path(__file__).resolve().parent.parent

    def test_the_audited_copy_changes_only_the_forks(self) -> None:
        text = (self.NODE / "Cargo.lock").read_text(encoding="utf-8")
        forks = audit.load_forks(self.NODE / "third_party" / "forks.json")
        policy = audit.load_policy(audit.DEFAULT_POLICY)
        original = lock_packages(text)
        fork_keys = {(f.lock_name, f.lock_version) for f in forks}
        workspace = {(p["name"], p["version"]) for p in original if "source" not in p} - fork_keys
        audited = audit.audited_lockfile(text, forks, workspace, policy.non_registry)
        self.assertEqual(audit.render_lock(audit.parse_lock(text)), text)
        after = lock_packages(audited.text)
        self.assertEqual(len(after), len(original))
        for before, now in zip(original, after):
            if (before["name"], before["version"]) in fork_keys:
                fork = [f for f in forks if (f.lock_name, f.lock_version) == (before["name"], before["version"])][0]
                self.assertEqual((now["name"], now["version"], now.get("source"), now.get("checksum")),
                                 (fork.name, fork.version, CRATES_IO, fork.crate_sha256))
                self.assertEqual(now["dependencies"], before["dependencies"])
            else:
                self.assertEqual(now, before)
        self.assertEqual(
            sorted(f"{name} {version}" for name, version in audited.forks.values()),
            ["arti-client 0.47.0", "igd-next 0.17.1", "libsqlite3-sys 0.38.2", "saturating-time 0.5.0",
             "secret-service 2.0.2"],
        )

    RSA_TIMING = ("RUSTSEC-2023-0071", "rsa", "0.9.10")
    SQLITE_WAL = ("RUSTSEC-2026-0459", "libsqlite3-sys", "0.38.2")

    def lock_users(self, packages: list[dict], name: str) -> set[str]:
        """The packages of the lock that name `name` as a dependency."""
        return {p["name"] for p in packages if any(d.split(" ")[0] == name for d in p["dependencies"])}

    def test_the_policy_accepts_only_the_rsa_timing_and_sqlite_wal_advisories(self) -> None:
        policy = audit.load_policy(audit.DEFAULT_POLICY)
        self.assertEqual(set(policy.active), {self.RSA_TIMING, self.SQLITE_WAL})
        # rsa 0.9.10 reaches the build only through Arti, which only verifies
        # RSA signatures; RUSTSEC-2023-0071 needs private key operations.
        self.assertIn("verif", policy.active[self.RSA_TIMING]["reachability"])

    def test_the_sqlite_wal_acceptance_holds_only_for_ravens_own_stores(self) -> None:
        # RUSTSEC-2026-0459 needs a database file and a -wal file that a less
        # trusted party wrote. The acceptance holds only while SQLite reaches
        # the build through rusqlite for the two users its text reviews:
        # raven-core (Raven's own stores) and Arti's tor-dirmgr (the Tor
        # directory cache), both inside the private data directory. A third
        # user fails here and is reviewed first. The fix (SQLite 3.54.0 in
        # libsqlite3-sys 0.39.0) needs rusqlite 0.41, which tor-dirmgr does
        # not accept, so the entry is short on purpose and is reviewed again
        # when Arti moves or the vendored fork carries the newer SQLite.
        policy = audit.load_policy(audit.DEFAULT_POLICY)
        entry = policy.active[self.SQLITE_WAL]
        for words in ("private data directory", "raven-core", "tor-dirmgr", "tor/cache"):
            self.assertIn(words, entry["reachability"])
        for words in ("libsqlite3-sys 0.39.0", "rusqlite 0.41", "tor-dirmgr"):
            self.assertIn(words, entry["reason"])
        packages = lock_packages((self.NODE / "Cargo.lock").read_text(encoding="utf-8"))
        self.assertEqual([p["version"] for p in packages if p["name"] == "libsqlite3-sys"],
                         ["0.38.2+raven.sqlcipher.4.17.0"])
        self.assertEqual(self.lock_users(packages, "libsqlite3-sys"), {"rusqlite"})
        self.assertEqual(self.lock_users(packages, "rusqlite"), {"raven-core", "tor-dirmgr"})
        self.assertEqual(self.lock_users(packages, "tor-dirmgr"), {"arti-client"})

    def test_the_policy_excepts_only_the_lock_only_crypto_bigint_advisory(self) -> None:
        # RUSTSEC-2026-0387 is fixed only in crypto-bigint 0.7.6, which
        # elliptic-curve 0.13 cannot use. The exception holds only while the
        # lock names crypto-bigint 0.5.5 for nothing but the optional NIST
        # curve key types of Arti's key format crate, which no Raven build
        # turns on (the audit itself checks that it is in no build graph).
        policy = audit.load_policy(audit.DEFAULT_POLICY)
        key = ("RUSTSEC-2026-0387", "crypto-bigint", "0.5.5")
        self.assertEqual(set(policy.inactive), {key})
        self.assertIn("elliptic-curve 0.13.8", policy.inactive[key]["reason"])
        packages = lock_packages((self.NODE / "Cargo.lock").read_text(encoding="utf-8"))

        def users(name: str) -> set[str]:
            return self.lock_users(packages, name)

        self.assertEqual([p["version"] for p in packages if p["name"] == "crypto-bigint"], ["0.5.5"])
        self.assertEqual(users("crypto-bigint"), {"elliptic-curve"})
        curves = {"p256", "p384", "p521"}
        self.assertEqual(users("elliptic-curve"), curves | {"ecdsa", "primeorder"})
        self.assertEqual(users("ecdsa"), curves)
        self.assertEqual(users("primeorder"), curves)
        for curve in sorted(curves):
            self.assertEqual(users(curve), {"ssh-key-fork-arti"}, curve)


